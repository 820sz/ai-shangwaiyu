/// 翻译纪律(v2.12.2,2026-10-20 用户原话)。
///
/// 用户原话:「翻译时,(无论是词汇板块还是追问里面的翻译),都一定要优先保证
/// 对翻译目标语本身的专业度和严谨度,不能刻意为了追求"中文表达习惯/通俗易懂"
/// 就牺牲了严谨度(尤其是涉及到学术/专业知识时),当然也不是说就只有"硬核",
/// 翻译的流畅度和"地道易懂"是服务于原文意思的表达,而不是对立或者舍弃」。
///
/// 为什么抽成**一条常量**而不是在每条提示词里各写一句:
/// - 项目里会产出译文的地方有 7 条链路(逐段翻译、整页翻译、词汇释义、
///   AI 补全、追问、快捷回复、精读导读/回译答案),各写一套必然口径不一;
///   用户要求的是"都一定要",只有同一段约束才谈得上统一;
/// - 这段话是**优先级规则**,不是文风建议。模型最容易犯的错不是"译错词",
///   而是为了顺口把 may 译成"会"、把 only 吞掉、把限定从句合并 ——
///   所以逐条写"哪些不许动",并明确它压过提示词里其它"通俗/地道"表述;
/// - 以后用户再收紧/放宽口径,只改这里一处,不会漏掉某条链路。
///
/// 插入方式:放在 system prompt 的翻译要求之后、输出格式要求之前;
/// **不要**动任何 JSON 字段名或段数约定(调用方按固定结构解析,改结构=整批报废)。
class TranslationPolicy {
  TranslationPolicy._();

  static const String discipline = '''翻译纪律(与"通顺/地道"冲突时,以下各条优先):
1. **准确、专业 > 流畅**:先保证原文信息不丢失、不增补、不改变;流畅只用来让译文
   读起来是自然的中文,不允许为了顺口、好懂而改写原意。
2. **术语用学界/行业通用译法**:学术、专业、技术内容必须用该领域通行的中文术语
   (如 marginal utility → 边际效用,opportunity cost → 机会成本,selection bias →
   选择偏差),不得改成口语化解释或近似说法;读者可能不熟时,可在术语后用括号
   补原文,如「边际效用(marginal utility)」。拿不准译名时,保留原文并给出通用
   直译,不要自创看似专业的词。
3. **限定、否定、时态、情态、程度一个都不能含糊**:may/might/could 的可能语气,
   can 的能力/许可含义,not/never/hardly 的否定范围,only/merely/at least 的限定,
   过去时与完成体的时间关系,比较级与最高级的程度,都要在中文里明确落出来;
   宁可句子长一点,也不许合并或省略。
4. **保持原句的逻辑关系**:因果、转折、条件、让步、指代对象必须与原文一致;
   不要把因果改写成并列,不要把条件句译成陈述句,不要把原文的保留/讽刺语气
   译成肯定。
5. **流畅只做"中文可读"这一件事**:调整语序、断句、省略重复主语可以;
   增加原文没有的解释、删掉插入语、把专有名词意译成泛称、把数字/单位改成
   约数,都不可以。
6. **格式按本题要求**:JSON 字段名、段数、顺序、空行等一律不变;除题目明确
   要求外,不要加译者注、不要加解释、不要中英双语并列。

以上六条优先于本提示词里任何"通俗易懂/符合中文表达习惯/地道/顺口"之类的
表述;两者冲突时,以这六条为准。''';
}
